"""
browserbot/agents/pattern_extractor/confirmer.py — Step 3.2: Parameter Confirmation.

RESPONSIBILITY
--------------
This module implements the human-in-the-loop safety net for Phase 3.

After the Pattern Extractor produces an ExtractorOutput, the user sees each
identified parameter and can:

  1. Accept it as-is          [Y / Enter]
  2. Rename it                [r]
  3. Reject it (remove it)    [n]
  4. Add a missed parameter   (offered after all parameters are reviewed)

The confirmed result is a new ExtractorOutput with only accepted/renamed
parameters.  Rejected parameters are silently dropped.  Added parameters
are appended at the end.

DESIGN PRINCIPLES
-----------------
- No downstream artifacts are generated by this step.
- The confirmer does NOT call the LLM again.
- The confirmed output validates against the same schema as the extractor output.
- The confirmer is a pure CLI interaction — no GUI, no web UI.
- Keyboard shortcuts follow common CLI conventions (Y/n/r).

WHY HUMAN-IN-THE-LOOP
-----------------------
Local open-weight models (llama3.1:8b) are reliable but not perfect. The
confirmation step is the "safety net" described in the execution plan:

    > "build a simple confirmation step: show the LLM's guessed parameters,
    >  let the user accept, rename, or add a missed one, before generation
    >  proceeds."

This step is more valuable with smaller local models than with frontier
models because local models drift more on edge cases (unusual field names,
multi-form workflows, re-confirmation password fields).

NON-INTERACTIVE MODE
--------------------
When `auto_confirm=True`, all parameters are accepted without prompting.
This is useful for:
  - Automated tests
  - Pipeline integration (CI/CD)
  - Dry-run smoke tests
"""

from __future__ import annotations

from dataclasses import dataclass, field

from browserbot.agents.pattern_extractor.models import (
    ExtractedParameter,
    ExtractorOutput,
    ExtractorOutputValidator,
)
from browserbot.logging import get_logger

log = get_logger(__name__)

# ANSI colours for terminal output (degrade gracefully when not supported)
_BOLD = "\033[1m"
_GREEN = "\033[32m"
_YELLOW = "\033[33m"
_RED = "\033[31m"
_CYAN = "\033[36m"
_RESET = "\033[0m"


# ---------------------------------------------------------------------------
# Confirmed output dataclass
# ---------------------------------------------------------------------------


@dataclass
class ConfirmedOutput:
    """
    Result of the parameter confirmation step.

    Contains the final list of parameters the user accepted/renamed/added,
    plus the unchanged fixed_step_indices and workflow_description from the
    original ExtractorOutput.

    This is the authoritative workflow definition that Phase 4 will consume.
    """

    parameters: list[ExtractedParameter] = field(default_factory=list)
    fixed_step_indices: list[int] = field(default_factory=list)
    workflow_description: str | None = None

    def to_extractor_output(self) -> ExtractorOutput:
        """
        Convert to an ExtractorOutput for schema validation before downstream use.
        """
        return ExtractorOutput(
            parameters=self.parameters,
            fixed_step_indices=self.fixed_step_indices,
            workflow_description=self.workflow_description,
        )


# ---------------------------------------------------------------------------
# CLI helpers
# ---------------------------------------------------------------------------


def _print_header(text: str) -> None:
    print(f"\n{_BOLD}{_CYAN}{'-' * 60}{_RESET}")
    print(f"{_BOLD}{_CYAN}{text}{_RESET}")
    print(f"{_BOLD}{_CYAN}{'-' * 60}{_RESET}")


def _print_parameter(index: int, param: ExtractedParameter) -> None:
    sensitive_tag = f" {_RED}[SENSITIVE]{_RESET}" if param.is_sensitive else ""
    print(
        f"\n  {_BOLD}[{index + 1}]{_RESET} "
        f"{_BOLD}{_GREEN}{param.name}{_RESET}{sensitive_tag}"
    )
    print(f"       Example value : {_YELLOW}{param.example_value!r}{_RESET}")
    print(f"       Step index    : {param.log_step_index}")
    if param.description:
        print(f"       Description   : {param.description}")


def _prompt_choice(prompt: str, valid: tuple[str, ...]) -> str:
    """Prompt the user for one of the valid choices. Loops until valid input."""
    while True:
        raw = input(prompt).strip().lower()
        if raw in valid:
            return raw
        if not raw and "y" in valid:
            return "y"   # Default to 'y' on empty Enter
        print(f"  Please enter one of: {', '.join(valid)}")


def _prompt_name(prompt: str) -> str:
    """Prompt for a snake_case parameter name. Validates format."""
    import re
    while True:
        name = input(prompt).strip()
        if re.match(r"^[a-z][a-z0-9_]*$", name):
            return name
        print("  Name must be snake_case (lowercase letters, digits, underscores; start with a letter).")


# ---------------------------------------------------------------------------
# Main confirmer function
# ---------------------------------------------------------------------------


def confirm_parameters(
    extractor_output: ExtractorOutput,
    *,
    auto_confirm: bool = False,
) -> ConfirmedOutput:
    """
    Walk the user through reviewing each extracted parameter.

    Args:
        extractor_output: The raw output from the Pattern Extractor.
        auto_confirm:     If True, accept all parameters without prompting.

    Returns:
        A :class:`ConfirmedOutput` with the user's decisions applied.
    """
    log.info(
        "Parameter confirmation started",
        extra={
            "parameters": len(extractor_output.parameters),
            "auto_confirm": auto_confirm,
        },
    )

    confirmed_params: list[ExtractedParameter] = []

    # ---- Review extracted parameters ----
    if not extractor_output.parameters:
        _print_header("BrowserBot — Parameter Review")
        print(f"\n  {_YELLOW}No parameters were identified in this workflow.{_RESET}")
        print("  This means the workflow has no dynamic inputs (all steps are fixed).")
    else:
        _print_header("BrowserBot — Parameter Review")
        print(
            f"\n  The Pattern Extractor identified "
            f"{_BOLD}{len(extractor_output.parameters)}{_RESET} parameter(s).\n"
        )
        print("  For each parameter, choose:")
        print(f"    {_BOLD}[Y / Enter]{_RESET} Accept")
        print(f"    {_BOLD}[r]{_RESET}         Rename")
        print(f"    {_BOLD}[n]{_RESET}         Reject (remove this parameter)")

        for i, param in enumerate(extractor_output.parameters):
            _print_parameter(i, param)

            if auto_confirm:
                print(f"  -> {_GREEN}Auto-accepted{_RESET}")
                confirmed_params.append(param)
                log.info(
                    "Parameter auto-accepted",
                    extra={"param_name": param.name, "step_idx": param.log_step_index},
                )
                continue

            choice = _prompt_choice(
                f"\n  Confirm? [{_BOLD}Y{_RESET}/n/r]: ",
                ("y", "n", "r", ""),
            )

            if choice in ("y", ""):
                confirmed_params.append(param)
                print(f"  -> {_GREEN}Accepted{_RESET}: {param.name}")
                log.info(
                    "Parameter accepted",
                    extra={"param_name": param.name, "step_idx": param.log_step_index},
                )

            elif choice == "n":
                print(f"  -> {_RED}Rejected{_RESET}: {param.name}")
                log.info(
                    "Parameter rejected",
                    extra={"param_name": param.name, "step_idx": param.log_step_index},
                )

            elif choice == "r":
                new_name = _prompt_name(
                    f"  New name for '{param.name}' (snake_case): "
                )
                renamed = ExtractedParameter(
                    name=new_name,
                    example_value=param.example_value,
                    log_step_index=param.log_step_index,
                    description=param.description,
                    is_sensitive=param.is_sensitive,
                )
                confirmed_params.append(renamed)
                print(f"  -> {_YELLOW}Renamed{_RESET}: {param.name} -> {new_name}")
                log.info(
                    "Parameter renamed",
                    extra={
                        "original_name": param.name,
                        "renamed_to": new_name,
                        "step_idx": param.log_step_index,
                    },
                )

    # ---- Offer to add missing parameters ----
    if not auto_confirm:
        print(f"\n  {_BOLD}Add a missing parameter?{_RESET}")
        while True:
            add_more = _prompt_choice(
                f"  Add parameter? [{_BOLD}y{_RESET}/N]: ",
                ("y", "n", ""),
            )
            if add_more in ("n", ""):
                break

            print("\n  Enter details for the new parameter:")
            name = _prompt_name("    Name (snake_case): ")
            example = input("    Example value   : ").strip()
            step_index_str = input("    Step index (from Action Log): ").strip()
            try:
                step_index = int(step_index_str)
            except ValueError:
                print("  Invalid step index — skipping.")
                continue

            description = input("    Description (optional, press Enter to skip): ").strip() or None

            new_param = ExtractedParameter(
                name=name,
                example_value=example,
                log_step_index=step_index,
                description=description,
                is_sensitive=False,
            )
            confirmed_params.append(new_param)
            print(f"  -> {_GREEN}Added{_RESET}: {name}")
            log.info(
                "Parameter added by user",
                extra={"param_name": name, "step_idx": step_index},
            )

    # ---- Validate the confirmed output ----
    result = ConfirmedOutput(
        parameters=confirmed_params,
        fixed_step_indices=extractor_output.fixed_step_indices,
        workflow_description=extractor_output.workflow_description,
    )

    extractor_output_obj = result.to_extractor_output()
    validator = ExtractorOutputValidator()
    validator.assert_valid(
        extractor_output_obj.model_dump_for_schema(),
        label="confirmed_output",
    )

    # ---- Summary ----
    _print_header("Confirmation Complete")
    print(f"\n  {_BOLD}{len(confirmed_params)}{_RESET} parameter(s) confirmed:")
    for p in confirmed_params:
        print(f"    * {_GREEN}{p.name}{_RESET} = {_YELLOW}{p.example_value!r}{_RESET}")

    if not confirmed_params:
        print(f"  {_YELLOW}(no dynamic parameters — this workflow is fully static){_RESET}")

    log.info(
        "Parameter confirmation complete",
        extra={
            "confirmed": len(confirmed_params),
            "workflow_description": result.workflow_description,
        },
    )

    return result
